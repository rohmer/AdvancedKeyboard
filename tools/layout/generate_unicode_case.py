#!/usr/bin/env python3
"""Generate compact, locale-independent Unicode case maps (not case folding).

Python's Unicode database supplies full scalar mappings, including SS for sharp
S. Constant-offset sequences are packed into ranges; one-to-many mappings stay
explicit. Regeneration records the Unicode version, so changes are reviewable.
"""
from pathlib import Path
import unicodedata


def tables(operation):
    simple, expanded = [], []
    for scalar in range(0x110000):
        mapped = getattr(chr(scalar), operation)()
        if mapped == chr(scalar):
            continue
        values = [ord(value) for value in mapped]
        if len(values) == 1:
            simple.append((scalar, values[0] - scalar))
        else:
            assert len(values) <= 3
            expanded.append((scalar, values))
    ranges, index = [], 0
    while index < len(simple):
        start, delta = simple[index]
        end, step = start, 1
        if index + 1 < len(simple) and simple[index + 1][1] == delta:
            gap = simple[index + 1][0] - start
            if gap in (1, 2):
                step = gap
        index += 1
        while index < len(simple) and simple[index] == (end + step, delta):
            end += step
            index += 1
        ranges.append((start, end, delta, step))
    return ranges, expanded


def generate():
    lines = [f"/* Generated by layout/generate_unicode_case.py; Unicode {unicodedata.unidata_version}. */"]
    for name, operation in (("Upper", "upper"), ("Lower", "lower")):
        ranges, expansions = tables(operation)
        lines.append(f"static const case_range_t k{name}Ranges[] = {{")
        lines.extend(f"    {{0x{first:X}, 0x{last:X}, {delta}, {step}}}," for first, last, delta, step in ranges)
        lines.append("};")
        lines.append(f"static const case_expansion_t k{name}Expansions[] = {{")
        for scalar, values in expansions:
            padded = values + [0] * (3 - len(values))
            lines.append(f"    {{0x{scalar:X}, {{{', '.join(f'0x{value:X}' for value in padded)}}}, {len(values)}}},")
        lines.append("};")
    Path(__file__).resolve().parents[2].joinpath("src/UnicodeCase.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
