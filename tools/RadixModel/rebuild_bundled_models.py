"""Rebuild a bundled catalog and optional built-in model as NGTR v4/NGIX v2.

Re-encoding preserves the trained terminal counts and vocabulary. It does not
retrain, prune to a new budget, or manufacture language-model probabilities.
All paths are explicit so the same tool works in the standalone source tree.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import uuid
import zipfile


def digest(data):
    return hashlib.sha256(data).hexdigest()


def identity(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return f"trie-{value:016x}"


def read_builder(path):
    spec = importlib.util.spec_from_file_location("bundled_ngix", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def format_version(data):
    if len(data) < 16 or data[:4] != b"NGTR":
        raise ValueError("Expected a complete NGTR header")
    version = struct.unpack_from("<I", data, 4)[0]
    if version not in (2, 3, 4):
        raise ValueError("Unsupported NGTR format version")
    return version


def encode(data, builder, converter, scratch):
    version = format_version(data)
    index = bytes(builder.build_index(data))
    if version == 4:
        return data, index
    scratch.mkdir(parents=True)
    source, source_index = scratch / "source.ngtr", scratch / "source.ngix"
    output, output_index = scratch / "model.ngtr", scratch / "model.ngix"
    source.write_bytes(data)
    source_index.write_bytes(index)
    subprocess.run([str(converter), str(source), str(source_index) if index else "-",
                    str(output), str(output_index)], check=True, capture_output=True, text=True)
    encoded, encoded_index = output.read_bytes(), output_index.read_bytes()
    if format_version(encoded) != 4 or encoded_index[:8] != b"NGIX\x02\0\0\0":
        raise ValueError("Converter did not produce NGTR v4 and NGIX v2")
    if bytes(builder.build_index(encoded)) != encoded_index:
        raise ValueError("Native/Python NGIX bytes disagree")
    original_nodes = struct.unpack_from("<I", data, 8)[0]
    if struct.unpack_from("<I", encoded, 12)[0] != original_nodes:
        raise ValueError("Lossless conversion changed the logical node count")
    return encoded, encoded_index


def describe(record, original, data, index):
    result = dict(record)
    result.update(sourceFormatVersion=record.get("sourceFormatVersion", format_version(original)),
                  sourceBytes=record.get("sourceBytes", len(original)),
                  sourceSHA256=record.get("sourceSHA256", digest(original)),
                  sourceNodeCount=record.get("sourceNodeCount", struct.unpack_from("<I", original, 12 if format_version(original) == 4 else 8)[0]),
                  formatVersion=4, indexVersion=2, bytes=len(data), indexBytes=len(index),
                  sha256=digest(data), indexSHA256=digest(index),
                  nodeCount=struct.unpack_from("<I", data, 12)[0],
                  physicalNodeCount=struct.unpack_from("<I", data, 8)[0],
                  projectTrieId=identity(data))
    return result


def catalog_include(records):
    lines = ["// Generated from catalog.json; do not edit separately."]
    for record in records:
        values = [json.dumps(record[key], ensure_ascii=True) for key in ("id", "language", "name", "sourceName")]
        values += [str(record["sizeKiB"]), str(record["bytes"])]
        values += [json.dumps(record[key]) for key in ("filename", "projectTrieId")]
        lines.append("    {" + ", ".join(values) + "},")
    return ("\n".join(lines) + "\n").encode()


def builtin_include(data, index):
    lines = ["// Generated by rebuild_bundled_models.py; see models/PROVENANCE.md."]
    for symbol, image in (("kBuiltinTrie", data), ("kBuiltinIndex", index)):
        lines.append("static constexpr uint8_t " + symbol + "[] = {")
        for offset in range(0, len(image), 16):
            lines.append("    " + ",".join(f"0x{value:02x}" for value in image[offset:offset + 16]) + ",")
        lines.append("};")
    return ("\n".join(lines) + "\n").encode()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name("." + path.name + ".rebuild-" + uuid.uuid4().hex + ".tmp")
    try:
        with temporary.open("xb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def publish(outputs, expected, backup_dir):
    changes = {path: data for path, data in outputs.items() if expected[path] != data}
    for path, before in expected.items():
        if (path.read_bytes() if path.exists() else None) != before:
            raise ValueError("File changed during rebuild; preserved: " + str(path))
    if not changes:
        return None
    backup_dir.mkdir(parents=True, exist_ok=True)
    backup = backup_dir / (datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8] + ".zip")
    with zipfile.ZipFile(backup, "x", zipfile.ZIP_DEFLATED) as archive:
        entries = []
        for number, path in enumerate(changes):
            name = f"before/{number}-{path.name}"
            if expected[path] is not None:
                archive.writestr(name, expected[path])
            entries.append({"path": str(path), "backup": name if expected[path] is not None else None})
        archive.writestr("manifest.json", json_bytes(entries))
    completed = []
    try:
        for path, data in changes.items():
            if (path.read_bytes() if path.exists() else None) != expected[path]:
                raise ValueError("File changed before publication; preserved: " + str(path))
            atomic_write(path, data)
            completed.append(path)
        for path, data in outputs.items():
            if path.read_bytes() != data:
                raise ValueError("Published file changed: " + str(path))
    except Exception:
        for path in reversed(completed):
            if path.exists() and path.read_bytes() == changes[path]:
                if expected[path] is None:
                    path.unlink()
                else:
                    atomic_write(path, expected[path])
        raise
    return str(backup)


def rebuild(args):
    catalog_path = args.catalog.resolve()
    catalog_data = catalog_path.read_bytes()
    catalog = json.loads(catalog_data)
    if catalog.get("version") != 1 or not catalog.get("models"):
        raise ValueError("Expected a version 1 bundled model catalog")
    builder = read_builder(args.index_builder.resolve())
    converter = args.converter.resolve()
    if not converter.is_file():
        raise ValueError("Build the native radix converter first: " + str(converter))
    outputs, expected, summaries, records = {}, {catalog_path: catalog_data}, [], []
    for generated in (args.compiled_catalog, args.builtin_include):
        if generated:
            path = generated.resolve()
            expected[path] = path.read_bytes() if path.exists() else None
    model_root = (catalog_path.parent / "models").resolve()

    def output(path, data):
        path = path.resolve()
        if path in outputs:
            raise ValueError("Colliding output path: " + str(path))
        if path not in expected:
            expected[path] = path.read_bytes() if path.exists() else None
        outputs[path] = data

    args.work_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="rebuild-", dir=args.work_dir) as temporary:
        for number, record in enumerate(catalog["models"]):
            filename = record["filename"]
            path = model_root / filename
            if Path(filename).name != filename or "/" in filename or "\\" in filename or not path.resolve().is_relative_to(model_root):
                raise ValueError("Model filename escapes the catalog")
            original = path.read_bytes()
            expected[path.resolve()] = original
            if len(original) != record["bytes"] or digest(original) != record["sha256"]:
                raise ValueError("Model does not match catalog: " + filename)
            old_index = bytes(builder.build_index(original))
            data, index = encode(original, builder, converter, Path(temporary) / str(number))
            records.append(describe(record, original, data, index))
            output(path, data)
            summaries.append(dict(model=filename, previousBytes=len(original) + len(old_index),
                                  bytes=len(data) + len(index)))
        if args.builtin_dir:
            directory = args.builtin_dir.resolve()
            source = directory / "enUS16.ngtr"
            original = source.read_bytes()
            expected[source] = original
            metadata_path = directory / "builtin.json"
            metadata_data = metadata_path.read_bytes() if metadata_path.exists() else None
            expected[metadata_path] = metadata_data
            old_index = bytes(builder.build_index(original))
            index_path = directory / "enUS16.ngix"
            if index_path.read_bytes() != old_index:
                raise ValueError("Built-in model/index mismatch")
            expected[index_path] = old_index
            data, index = encode(original, builder, converter, Path(temporary) / "builtin")
            metadata = json.loads(metadata_data) if metadata_data is not None else dict(
                id="builtin-en-us", language="en-US", name="Built-in English", sizeKiB=16,
                filename="enUS16.ngtr", sourceName="ESPOS Trie/enUS16.ngtr")
            metadata = describe(metadata, original, data, index)
            # The reserved built-in project identifier is independent of its encoding.
            metadata["projectTrieId"] = "builtin-en-us"
            output(source, data)
            output(index_path, index)
            output(metadata_path, json_bytes(metadata))
            output(args.builtin_include, builtin_include(data, index))
            summaries.append(dict(model="builtin-en-us", previousBytes=len(original) + len(old_index),
                                  bytes=len(data) + len(index)))
    catalog["models"] = records
    catalog["encoding"] = {"formatVersion": 4, "indexVersion": 2, "method": "lossless-reencode",
                           "profiles": "original nominal sizes; vocabulary and counts preserved"}
    output(catalog_path, json_bytes(catalog))
    if args.compiled_catalog:
        output(args.compiled_catalog, catalog_include(records))
    changed = sum(expected[path] != data for path, data in outputs.items())
    backup = publish(outputs, expected, args.work_dir / "backups") if args.write else None
    return dict(status="rebuilt" if args.write else "planned", models=len(summaries), changedFiles=changed,
                previousBytes=sum(item["previousBytes"] for item in summaries),
                bytes=sum(item["bytes"] for item in summaries), backup=backup, profiles=summaries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--converter", required=True, type=Path)
    parser.add_argument("--index-builder", required=True, type=Path)
    parser.add_argument("--compiled-catalog", type=Path)
    parser.add_argument("--builtin-dir", type=Path)
    parser.add_argument("--builtin-include", type=Path)
    parser.add_argument("--work-dir", required=True, type=Path, help="ignored build folder for staging/backups")
    parser.add_argument("--write", action="store_true", help="publish only after every model validates")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    if bool(args.builtin_dir) != bool(args.builtin_include):
        parser.error("--builtin-dir and --builtin-include must be supplied together")
    try:
        result = rebuild(args)
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_bytes(json_bytes(result))
        print(json.dumps(result, indent=2))
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Rebuild failed: {error}\n" + (getattr(error, "stderr", "") or ""))


if __name__ == "__main__":
    main()
